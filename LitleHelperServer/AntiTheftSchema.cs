using Microsoft.EntityFrameworkCore;

namespace LitleHelperServer;

public static class AntiTheftSchema
{
    public static async Task EnsureAsync(HelperDb db)
    {
        bool pg = db.Database.IsNpgsql();
        string boolean = pg ? "BOOLEAN NOT NULL DEFAULT false" : "INTEGER NOT NULL DEFAULT 0";
        string time = pg ? "timestamp with time zone" : "TEXT";
        string dbl = pg ? "DOUBLE PRECISION" : "REAL";
        string identityPk = pg ? "integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER PRIMARY KEY AUTOINCREMENT";

        await ChatBroadcasts.Column(db, "Computers", "IsPortable", boolean);
        await ChatBroadcasts.Column(db, "Computers", "BatteryPercent", "INTEGER NOT NULL DEFAULT 100");
        await ChatBroadcasts.Column(db, "Computers", "IsCharging", boolean);
        await ChatBroadcasts.Column(db, "Computers", "LastSsid", "TEXT NOT NULL DEFAULT ''");
        await ChatBroadcasts.Column(db, "Computers", "LastBssid", "TEXT NOT NULL DEFAULT ''");
        await ChatBroadcasts.Column(db, "Computers", "HardwareUuid", "TEXT NOT NULL DEFAULT ''");
        await ChatBroadcasts.Column(db, "Computers", "IsLockedDown", boolean);
        await ChatBroadcasts.Column(db, "Computers", "LockLevelScreen", boolean);
        await ChatBroadcasts.Column(db, "Computers", "LockLevelSession", boolean);
        await ChatBroadcasts.Column(db, "Computers", "LockLevelBitLocker", boolean);
        await ChatBroadcasts.Column(db, "Computers", "LockMessage", "TEXT NOT NULL DEFAULT ''");
        await ChatBroadcasts.Column(db, "Computers", "BitLockerRecoveryTriggered", boolean);
        await ChatBroadcasts.Column(db, "Computers", "Latitude", $"{dbl} NULL");
        await ChatBroadcasts.Column(db, "Computers", "Longitude", $"{dbl} NULL");
        await ChatBroadcasts.Column(db, "Computers", "LocationAccuracy", "REAL NULL");
        await ChatBroadcasts.Column(db, "Computers", "LastLocationTime", $"{time} NULL");
        await ChatBroadcasts.Column(db, "Computers", "LocationAddress", "TEXT NOT NULL DEFAULT ''");

        await db.Database.ExecuteSqlRawAsync($"""
            CREATE TABLE IF NOT EXISTS "LaptopMovementLogs" (
                "Id" {identityPk},
                "ComputerId" INTEGER NOT NULL,
                "MachineName" TEXT NOT NULL DEFAULT '',
                "Timestamp" {time} NOT NULL,
                "ExternalIp" TEXT NOT NULL DEFAULT '',
                "Ssid" TEXT NOT NULL DEFAULT '',
                "Bssid" TEXT NOT NULL DEFAULT '',
                "VisibleNetworksJson" TEXT NOT NULL DEFAULT '[]',
                "EstimatedAddress" TEXT NOT NULL DEFAULT ''
            )
            """);
        await db.Database.ExecuteSqlRawAsync("CREATE INDEX IF NOT EXISTS \"IX_LaptopMovementLogs_ComputerId\" ON \"LaptopMovementLogs\" (\"ComputerId\")");
        await db.Database.ExecuteSqlRawAsync("CREATE INDEX IF NOT EXISTS \"IX_LaptopMovementLogs_Timestamp\" ON \"LaptopMovementLogs\" (\"Timestamp\")");

        await db.Database.ExecuteSqlRawAsync($"""
            CREATE TABLE IF NOT EXISTS "MobileDevices" (
                "Id" {identityPk},
                "DeviceId" TEXT NOT NULL DEFAULT '',
                "BrandModel" TEXT NOT NULL DEFAULT '',
                "SerialNumber" TEXT NOT NULL DEFAULT '',
                "Imei" TEXT NOT NULL DEFAULT '',
                "AndroidVersion" TEXT NOT NULL DEFAULT '',
                "ClientVersion" TEXT NOT NULL DEFAULT '',
                "AssignedUsername" TEXT NOT NULL DEFAULT '',
                "AssignedUserFullName" TEXT NOT NULL DEFAULT '',
                "BranchId" INTEGER NULL,
                "Department" TEXT NOT NULL DEFAULT '',
                "PhoneNumber" TEXT NOT NULL DEFAULT '',
                "SimIccid" TEXT NOT NULL DEFAULT '',
                "BatteryPercent" INTEGER NOT NULL DEFAULT 100,
                "IsCharging" {boolean},
                "CurrentIp" TEXT NOT NULL DEFAULT '',
                "CurrentWifiSsid" TEXT NOT NULL DEFAULT '',
                "CurrentWifiBssid" TEXT NOT NULL DEFAULT '',
                "Latitude" {dbl} NULL,
                "Longitude" {dbl} NULL,
                "LocationAccuracy" REAL NULL,
                "LastLocationTime" {time} NULL,
                "LocationAddress" TEXT NOT NULL DEFAULT '',
                "WireGuardPublicKey" TEXT NOT NULL DEFAULT '',
                "WireGuardInternalIp" TEXT NOT NULL DEFAULT '',
                "WireGuardHandshakeUtc" {time} NULL,
                "IsOnline" {boolean},
                "LastSeen" {time} NOT NULL,
                "IsLockedDown" {boolean},
                "LockLevelScreen" {boolean},
                "LockLevelPin" {boolean},
                "LockMessage" TEXT NOT NULL DEFAULT '',
                "TemporaryLockPin" TEXT NOT NULL DEFAULT '',
                "IsSirenActive" {boolean}
            )
            """);
        await db.Database.ExecuteSqlRawAsync("CREATE UNIQUE INDEX IF NOT EXISTS \"IX_MobileDevices_DeviceId\" ON \"MobileDevices\" (\"DeviceId\")");
    }
}
